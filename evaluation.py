# ==========================================================
# 補足（tips）を達成項目に結びつける
#   AIが tips の item を評価項目と少し違う文言で返すことがあるので、
#   記号・空白を除いた文字の2文字組の重なりで、いちばん近い達成項目に付ける。
#   アバター版 lib/evaluation.ts の tipsForAchieved と同じ処理
# ==========================================================
def _norm(text):
    import re
    return re.sub(r"[\s、。，．・,.（）()「」『』〜~：:；;／/]", "", str(text or ""))


def _bigram_sim(a, b):
    a, b = _norm(a), _norm(b)
    if not a or not b:
        return 0.0
    if a == b:
        return 1.0
    if a in b or b in a:
        return 0.9
    ga = [a[i:i + 2] for i in range(len(a) - 1)] or [a]
    rest = [b[i:i + 2] for i in range(len(b) - 1)] or [b]
    nb = len(rest)
    hit = 0
    for g in ga:
        if g in rest:
            rest.remove(g)
            hit += 1
    return 2 * hit / (len(ga) + nb)


def tips_for_achieved(evaluation_json):
    """達成項目 → 補足 の dict と、どの達成項目にも結びつかなかった補足のリストを返す"""
    achieved = list((evaluation_json or {}).get("achieved", []) or [])
    out, left = {}, []
    for t in (evaluation_json or {}).get("tips", []) or []:
        if not isinstance(t, dict) or not t.get("tip"):
            continue
        best, score = None, 0.0
        for a in achieved:
            s = _bigram_sim(t.get("item", ""), a)
            if s > score:
                best, score = a, s
        if best is not None and score >= 0.5:
            out[best] = (out[best] + " " + t["tip"]) if best in out else t["tip"]
        else:
            left.append(t["tip"])
    return out, left
