#   サブシナリオ名の先頭の業務名で評価項目を選ぶ（scenario_kind.py）。
DISEASES = ("がん", "高血圧症", "糖尿病", "心疾患", "脳血管障害", "精神神経疾患", "免疫・アレルギー疾患", "感染症")


def _by_disease(table, disease):
    for name, sc in table.items():
        if name.split("｜")[0][1:] == disease:
            return name.split("｜", 1)[1], sc
    raise KeyError(disease)


HOSPITAL_SCENARIOS = {}
for _d in DISEASES:
    HOSPITAL_SCENARIOS[f"{_d}（病院）"] = {
        f"{num}{kind}｜{title}": sc
        for num, kind, table in (("①", "初回面談", HOSPITAL_INTERVIEW),
                                 ("②", "服薬指導", HOSPITAL_MED),
                                 ("③", "退院時指導", HOSPITAL_DISCHARGE))
        for title, sc in [_by_disease(table, _d)]
    }
HOSPITAL_SCENARIOS["情報提供（病院）"] = HOSPITAL_INFO
