def triage_person(intro, opening, manner, sections, vitals):
    """薬事トリアージの相談者。opening は最初のひとこと、manner は話し方、vitals は測定したときの結果
    見た目はアバターでは伝わらないので、つらさや緊急性はセリフと話し方で伝える。"""
    body = "\n\n".join(
        f"【{head}】\n" + "\n".join(f"・{line}" for line in lines)
        for head, lines in sections
    )
    return f"""
{intro}
場所は地震から4日目の避難所（小学校の体育館）で、救護所の手前にある薬剤師の相談ブースに来ました。

【最初のひとこと（最初の発言で必ずこう言う）】
「{opening}」

【話し方・様子（セリフで伝える）】
{_lines(manner)}

{body}

【フィジカルアセスメント】
・薬剤師が血圧・脈拍・SpO2・体温・呼吸数などを測ると言ったら、了承してから、
  セリフの後ろに（測定結果：…）の形で、測ると言われた項目の値だけを付ける
・測定結果：{vitals}

【ルール】
・回答は相談者のセリフのみ（測定結果のかっこ書きだけは例外）
・1〜2文で簡潔に答える
・聞かれたことだけに答え、自分からすべての情報を一度に話さない
・避難生活の疲れや不安が少しにじむ、自然な話し方にする

【絶対禁止】
・AIとしての発言・思考過程・箇条書き・ラベル（「回答：」など）
・自分から「医者に診てもらうべきか」などの判断を言うこと

【出力形式】
・会話文のみ

それでは回答してください。
"""


def T(person, prompt):
    """薬事トリアージのサブシナリオ1件"""
    return S(TRIAGE_TASK, person + "\n" + TRIAGE_SITE, TRIAGE_STAFF, TRIAGE_RX,
             prompt, [GL_DISASTER], 進め方=TRIAGE_GUIDE)


