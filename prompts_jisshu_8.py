def _patient_rules():
    return """
【ルール】
・回答は患者のセリフのみ
・1〜2文で簡潔に答える
・聞かれたことだけに答え、自分からすべての情報を一度に話さない

【絶対禁止】
・AIとしての発言・思考過程・箇条書き・ラベル（「回答：」など）

【出力形式】
・会話文のみ

それでは回答してください。
"""


def _staff_rules(role):
    return f"""
※丁寧だが簡潔に、{role}として自然に話してください。
※自分からすべての情報を一度に話さず、聞かれたことに答えてください。
※考え方・思考過程・理由・THOUGHT・分析は一切出力しないでください。
※出力は{role}のセリフのみ。「回答：」などのラベルも付けない。
※1〜2文で答える。
"""


def patient(intro, sections):
    """患者役のプロンプト。sections は (見出し, [行, ...]) のリスト"""
    body = "\n\n".join(
        f"【{head}】\n" + "\n".join(f"・{line}" for line in lines)
        for head, lines in sections
    )
    return f"\n{intro}\n\n{body}\n{_patient_rules()}"


