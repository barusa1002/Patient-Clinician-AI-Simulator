def _staff(purpose, place=None, role="実習生"):
    head = f"薬局名：{place}\n" if place else ""
    return f"{head}職種：薬剤師\n立場：{role}\n目的：{purpose}"


def _sc(task, patient_info, staff_info, rx, prompt):
    return {
        "task_info": {"課題内容": task, "患者情報": patient_info,
                      "医療従事者情報": staff_info, "処方内容": rx},
        "prompt": prompt.strip("\n") + "\n",
    }


def _patient(intro, body):
    return ("あなたは患者役です。薬剤師の役は絶対に演じないでください。\n"
            + intro.strip() + "\n\n" + body.strip() + "\n" + _PATIENT_RULES)


