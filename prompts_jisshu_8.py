#   災害時の避難所で、救護所（医師）の手前で薬剤師が相談を受け、3つの群に振り分ける。
#   出典：厚生労働科学研究班「薬剤師のための災害対策マニュアル（改訂版）」令和6年3月 p.163
#        （日本災害医学会 PhDLS プロバイダーコースより一部改変の流れ図）
#     受診勧奨群（Ⅰ）：バイタルが不安定で医学的判断が必要な方
#     薬事対応群（Ⅱ）：基本的にバイタルが安定しており、常用薬やOTCで健康が管理できる方
#     情報提供群（Ⅲ）：薬物療法を必要としないと判断され、健康相談で対応できる方
#   手順：第一印象（異常→Ⅰ）→ 問診 → フィジカルアセスメント → 新たな症状
#     あり → 再評価：不安定→Ⅰ／安定→Ⅱ（Ⅱで対応できなければⅠ）
#     なし → 常用薬の希望：あり→再評価（不安定→Ⅰ／安定→Ⅱ）、なし→Ⅲ（情報提供で不十分ならⅡ）
#   アバターの見た目では伝わらないので、第一印象は「最初の訴えと話し方」で表す（2026-11-24）。
#   サブシナリオ名に正解の区分を書かない（学生に見えるため）。
#   正解は evaluation.py の EVALUATION_ANSWER_KEYS に置き、評価AIにだけ渡す。
