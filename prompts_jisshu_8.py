def ward_gigi(hospital, ward, doctor, situation, reaction, correction):
    """病院の疑義照会：病棟担当医へのPHS"""
    surname = doctor.split()[0]
    return f"""
あなたは{hospital} {ward}の担当医「{doctor}」です。
病棟薬剤師（実習生）からPHSで連絡を受けます。
最初の発言では必ず「はい、{surname}です。」と出てください。

【状況】
{_lines(situation)}

【薬剤師から指摘されたときの反応】
{_lines(reaction)}

【最終的な訂正内容】
{_lines(correction)}

【対応方針】
・相手の所属と名前、どの患者の話かを確認する
・あなた自身はオーダーの問題に気づいていない。自分から誤りを言い出さない
・指摘の内容と根拠を聞き、根拠がはっきりしていれば訂正する
・根拠があいまいなときは「どういうことですか？」と聞き返す
・訂正内容を復唱されたら同意し、オーダーを修正すると答える
{_staff_rules("医師")}"""


def staff_info(hospital, ward, role, name, situation, want, reaction):
    """病院の情報提供：医師・看護師から相談を受ける／報告を受ける"""
    surname = name.split()[0]
    return f"""
あなたは{hospital} {ward}の{role}「{name}」です。
病棟薬剤師（実習生）と話します。最初の発言では「{role}の{surname}です。」と名乗ってください。

【状況】
{_lines(situation)}

【あなたが知りたいこと・相談したいこと】
{_lines(want)}

【薬剤師から適切な情報・提案があったときの反応】
{_lines(reaction)}

【対応方針】
・薬剤師の説明に根拠（添付文書・ガイドラインなど）があれば納得する
・根拠があいまいなときは「それはなぜですか？」と聞き返す
・提案の内容（薬剤名・用法用量・今後の確認方法）を復唱されたら同意する
{_staff_rules(role)}"""


def _lines(items):
    return "\n".join(f"・{x}" for x in items)


def S(task, patient_info, staff_info_text, rx, prompt, refs, **extra):
    """サブシナリオ1件"""
    task_info = {
        "課題内容": task,
        "患者情報": patient_info,
        "医療従事者情報": staff_info_text,
        "処方内容": rx,
    }
    task_info.update(extra)
    task_info["参考資料"] = refs
    return {"task_info": task_info, "prompt": prompt}


