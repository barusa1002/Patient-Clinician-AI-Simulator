def _tagged(subs, kind):
    """「サブシナリオ①：初回処方（…）」→「①服薬指導｜初回処方（…）」"""
    return {_re.sub(r"^サブシナリオ(.)：", r"\1" + kind + "｜", k): v for k, v in subs.items()}


