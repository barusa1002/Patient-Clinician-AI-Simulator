# 評価保存（Supabase版）
# ==========================================================
def save_evaluation(user_id, scenario, subscenario, chat_history, evaluation_text,
                    prescription_notes=None, soap_notes=None):

    if user_id == "guest":
        return  # ゲストモードはDB保存しない

    try:
        eval_data = {
            "chat_history": chat_history,
            "result": evaluation_text,
        }
        if prescription_notes:
            eval_data["prescription_notes"] = prescription_notes
        if soap_notes:
            eval_data["soap_notes"] = soap_notes

        supabase.table("evaluations").insert({
            "user_id": user_id,
            "scenario": scenario,
            "subscenario": subscenario,
            "evaluation": eval_data,
        }).execute()

    except Exception as e:
        logger.error(f"save_evaluation error: {e}")

# ==========================================================
# 個人評価取得
# ==========================================================

def load_user_evaluations(user_id):

    if user_id == "guest":
        return []

    try:
        res = supabase.table("evaluations") \
            .select("*") \
            .eq("user_id", user_id) \
            .order("created_at", desc=True) \
            .execute()
        return res.data or []
    except Exception as e:
        logger.error(f"load_user_evaluations error: {e}")
        return []

