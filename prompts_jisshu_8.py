# ==========================================================
# 薬局実習：薬事トリアージ（薬局）
#   災害時の避難所で、救護所（医師）の手前で薬剤師が相談を受け、
#   PT1〜PT4に振り分ける。代表8疾患ではなく、フローの分岐ごとに1件ずつ置く。
#   出典：日本災害医学会 災害薬事標準テキスト「Pharmaceutical Triage」
#     第一印象で明らかに医師の診察を要する → PT1
#     常用薬希望あり → フィジカルアセスメント：不安定 → PT1／安定 → PT2
#     常用薬希望なし・対応を要する症状あり → OTC対応：不可 → PT1／可（患者の希望を確認）→ PT3
#     対応を要する症状なし → PT4
#   サブシナリオ名に正解の区分を書かない（学生に見えるため）。
#   正解は evaluation.py の EVALUATION_ANSWER_KEYS に置き、評価AIにだけ渡す。
# ==========================================================
GL_DISASTER = _ref("日本災害医学会（災害薬事標準テキスト）", "https://jadm.or.jp/")

TRIAGE_SITE = ("場所：市立みなみ小学校の体育館（避難所）\n"
               "状況：大きな地震から4日目。救護所（医師が診察）の入口に薬剤師の相談ブースがある")
TRIAGE_STAFF = ("職種：薬剤師\n立場：実習生（災害時を想定した練習）\n"
                "目的：薬事トリアージ（診察が必要な人だけを救護所に誘導する）")
TRIAGE_TASK = ("避難所の相談ブースに来た人の話を聞き、薬事トリアージを行ってください。"
               "第一印象・常用薬の希望・症状を順に確かめ、必要ならフィジカルアセスメント"
               "（血圧・脈拍・SpO2・体温・呼吸数の測定）を行うこと。"
               "対応を決めたら、相手にこの後どうするかを伝えてください。"
               "最後に、判定した区分を「判定：PT○（理由）」の形で入力すること。")
TRIAGE_RX = "処方箋なし（避難所での相談）"


def triage_person(intro, first_look, sections, vitals):
    """薬事トリアージの相談者。first_look は見た目、vitals は測定したときの結果"""
    body = "\n\n".join(
        f"【{head}】\n" + "\n".join(f"・{line}" for line in lines)
        for head, lines in sections
    )
    return f"""
{intro}
場所は地震から4日目の避難所（小学校の体育館）で、救護所の手前にある薬剤師の相談ブースに来ました。

【見た目（薬剤師から見える様子）】
{_lines(first_look)}

{body}

【フィジカルアセスメント】
・薬剤師が血圧・脈拍・SpO2・体温・呼吸数などを測ると言ったら、了承してから、
  セリフの後ろに（測定結果：…）の形で、測ると言われた項目の値だけを付ける
・測定結果：{vitals}

【「判定：」で始まる発言】
・薬剤師の記録なので、内容には触れず「はい。」とだけ答える

【ルール】
・回答は相談者のセリフのみ（測定結果のかっこ書きだけは例外）
・1〜2文で簡潔に答える
・聞かれたことだけに答え、自分からすべての情報を一度に話さない
・避難生活の疲れや不安が少しにじむ、自然な話し方にする

【絶対禁止】
・AIとしての発言・思考過程・箇条書き・ラベル（「回答：」など）
・自分から「医者に診てもらうべきか」などの判断を言うこと

【出力形式】
・会話文のみ

それでは回答してください。
"""


def T(person, prompt):
    """薬事トリアージのサブシナリオ1件"""
    return S(TRIAGE_TASK, person + "\n" + TRIAGE_SITE, TRIAGE_STAFF, TRIAGE_RX,
             prompt, [GL_DISASTER])


