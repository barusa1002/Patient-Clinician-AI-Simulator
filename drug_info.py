def lookup(drug_name: str):
    """薬品名からくすりのしおり情報を引く。該当がなければ None。"""
    if not drug_name:
        return None
    for key, info in DRUG_INFO.items():
        if key in drug_name:
            return info
    return None


def caution_lines(info: dict) -> list:
    """注意事項として表示する行を組み立てる（見出し＋箇条書き）"""
    if not info:
        return []

    lines = [("head", CAUTION_HEADER)]
    lines.append(("item", COMMON_ALLERGY))
    for item in info.get("伝えること", ()):
        lines.append(("item", item))
    lines.append(("item", COMMON_PREGNANCY))
    lines.append(("item", COMMON_OTHER))

    living = info.get("生活上の注意", ())
    if living:
        lines.append(("head", LIFESTYLE_HEADER))
        for item in living:
            lines.append(("item", item))

    return lines
