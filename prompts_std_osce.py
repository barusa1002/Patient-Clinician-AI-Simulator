def add_std_rules(prompt):
    """スタンダードモードの指示文に、役ごとの約束を付ける（二重には付けない）"""
    if "【この練習での約束" in prompt:
        return prompt
    if "電話応対シミュレーション" in prompt:
        rules = _STD_PHONE_RULES
    elif re.search(r"あなたは[^\n。]*医(（|です|師)", prompt):
        rules = _STD_DOCTOR_RULES
    else:
        rules = _STD_PATIENT_RULES
    return prompt.rstrip("\n") + "\n" + rules + _STD_OUTPUT_RULES


